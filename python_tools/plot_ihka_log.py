#!/usr/bin/env python3
"""
Synchronized 5-panel diagnostic plotter for BMW G30/G31 IHKA_G11 (2-zone or 4-zone) CSV logs
(generated by the G30/G31 IHKA Logger Android app). 2-zone logs have empty rear-duct columns, which are skipped.

Panels:
  1. Engine Coolant, Outside Ambient, Windshield Glass Temp (RLBS), Dew-Point Estimate & 12V Bus Voltage (twin axis)
  2. Evaporator Core Temp (with <2.0°C Icing / Cut-Out Zone & dT/dt spike detection) + Cabin Interior Temp + Target Setpoint
  3. Duct Temperatures: Front Vent L/R, Front Footwell L/R, Rear Vent L/R + Rear Footwell L/R (4-zone only) + PTC PCB Temp (°C)
  4. Aircon Settings & PTC Duty Cycle: PTC Heater Duty %, Blower Power %, Stratification L/R %, AUTO Mode, A/C & SYNC
  5. LIN Stepper Flap Positions (0-100%): Defrost, Front Footwell L, Front Mix L/R, Rear Mix L/R, Rear Dist L + Windshield RH%
"""

import argparse
import csv
import sys
from pathlib import Path
import numpy as np
import matplotlib.pyplot as plt


def load_ihka_csv(csv_path: Path):
    with csv_path.open("r", newline="") as f:
        reader = csv.DictReader(f)
        rows = list(reader)
        headers = reader.fieldnames or []

    if not rows:
        print(f"[!] CSV file '{csv_path}' contains no rows.", file=sys.stderr)
        sys.exit(1)

    def col_float(name: str) -> np.ndarray:
        arr = np.full(len(rows), np.nan, dtype=float)
        for i, r in enumerate(rows):
            val = (r.get(name) or "").strip()
            if val:
                try:
                    v = float(val)
                    # -999 marked "no sensor" in some earlier app builds
                    arr[i] = np.nan if v == -999 else v
                except ValueError:
                    pass
        return arr

    data = {col: col_float(col) for col in headers if col not in ("timestamp", "event_marker")}
    markers = [(r.get("event_marker") or "").strip() for r in rows]
    return data, markers


def detect_spikes(t: np.ndarray, y: np.ndarray, threshold_c_per_s: float = 2.5) -> np.ndarray:
    valid = np.isfinite(t) & np.isfinite(y)
    if np.count_nonzero(valid) < 3:
        return np.array([], dtype=int)
    dt_arr = np.diff(t)
    dy_arr = np.diff(y)
    with np.errstate(divide="ignore", invalid="ignore"):
        rate = np.abs(dy_arr / np.where(dt_arr > 0.05, dt_arr, np.nan))
    return np.where(rate >= threshold_c_per_s)[0] + 1


def calc_dewpoint(temp_c: np.ndarray, rh_pct: np.ndarray) -> np.ndarray:
    """Magnus-Tetens dew point approximation at the windshield surface."""
    out = np.full_like(temp_c, np.nan)
    valid = np.isfinite(temp_c) & np.isfinite(rh_pct) & (rh_pct > 1.0)
    if not np.any(valid):
        return out
    a, b = 17.27, 237.7
    t_v = temp_c[valid]
    rh_v = np.clip(rh_pct[valid], 1.0, 100.0)
    alpha = (a * t_v) / (b + t_v) + np.log(rh_v / 100.0)
    out[valid] = (b * alpha) / (a - alpha)
    return out


def main():
    parser = argparse.ArgumentParser(description="Plot a BMW G30/G31 IHKA_G11 CSV log (2-zone or 4-zone)")
    parser.add_argument("--csv", required=True, help="Path to ihka_log_YYYYMMDD_HHMMSS.csv (older logs: g31_ihka_4zone_...csv)")
    parser.add_argument("--spike-rate", type=float, default=2.5, help="Evap dT/dt spike alert threshold (°C/s)")
    parser.add_argument("--save", help="Optional PNG/PDF file path to export figure")
    args = parser.parse_args()

    csv_path = Path(args.csv)
    if not csv_path.exists():
        print(f"[!] File not found: {csv_path}", file=sys.stderr)
        sys.exit(1)

    data, markers = load_ihka_csv(csv_path)
    t = data.get("elapsed_s", np.arange(len(markers), dtype=float))
    t_min = t / 60.0

    batt_v = data.get("battery_v", np.full_like(t, np.nan))
    evap = data.get("evap_c", np.full_like(t, np.nan))
    cabin = data.get("cabin_c", np.full_like(t, np.nan))
    vent_fl = data.get("vent_fl_c", np.full_like(t, np.nan))
    vent_fr = data.get("vent_fr_c", np.full_like(t, np.nan))
    foot_fl = data.get("foot_fl_c", np.full_like(t, np.nan))
    foot_fr = data.get("foot_fr_c", np.full_like(t, np.nan))
    vent_rl = data.get("vent_rl_c", np.full_like(t, np.nan))
    vent_rr = data.get("vent_rr_c", np.full_like(t, np.nan))
    foot_rl = data.get("foot_rl_c", np.full_like(t, np.nan))
    foot_rr = data.get("foot_rr_c", np.full_like(t, np.nan))
    # 2-zone cars leave the rear duct columns empty
    zones = 4 if any(np.any(np.isfinite(a)) for a in (vent_rl, vent_rr, foot_rl, foot_rr)) else 2

    outside = data.get("outside_c", np.full_like(t, np.nan))
    ws_c = data.get("windshield_c", np.full_like(t, np.nan))
    ws_rh = data.get("windshield_rh", np.full_like(t, np.nan))
    ac_bar = data.get("ac_bar", np.full_like(t, np.nan))
    coolant = data.get("b58_coolant_c", np.full_like(t, np.nan))

    # Aircon Settings & PTC (0xD8DB, 0xD8D8, 0xA12A, 0xA128, 0xA12B)
    target_fl = data.get("target_fl_c", np.full_like(t, np.nan))
    target_fr = data.get("target_fr_c", np.full_like(t, np.nan))
    sync_act = data.get("sync_active", np.full_like(t, np.nan))
    ac_on = data.get("ac_on", np.full_like(t, np.nan))
    auto_flap_l = data.get("auto_flap_l", np.full_like(t, np.nan))
    blower_step_l = data.get("blower_step_l", np.full_like(t, np.nan))
    blower_pct_f = data.get("blower_pct_front", np.full_like(t, np.nan))
    blower_pct_r = data.get("blower_pct_rear", np.full_like(t, np.nan))
    ptc_duty = data.get("ptc_duty_pct", np.full_like(t, np.nan))
    ptc_temp = data.get("ptc_temp_c", np.full_like(t, np.nan))
    strat_l = data.get("strat_l_pct", np.full_like(t, np.nan))

    flap_def = data.get("flap_defrost_pct", np.full_like(t, np.nan))
    flap_vent_l = data.get("flap_vent_l_pct", np.full_like(t, np.nan))
    flap_vent_r = data.get("flap_vent_r_pct", np.full_like(t, np.nan))
    flap_foot_l = data.get("flap_foot_l_pct", np.full_like(t, np.nan))
    flap_foot_r = data.get("flap_foot_r_pct", np.full_like(t, np.nan))
    flap_r_dist_r = data.get("flap_rear_dist_r_pct", np.full_like(t, np.nan))
    flap_r_dist_l = data.get("flap_rear_dist_l_pct", np.full_like(t, np.nan))
    flap_mix_l = data.get("flap_mix_l_pct", np.full_like(t, np.nan))
    flap_mix_r = data.get("flap_mix_r_pct", np.full_like(t, np.nan))
    flap_r_mix_l = data.get("flap_rear_mix_l_pct", np.full_like(t, np.nan))
    flap_r_mix_r = data.get("flap_rear_mix_r_pct", np.full_like(t, np.nan))

    dew_c = calc_dewpoint(ws_c, ws_rh)

    print(f"\n=== G30/G31 IHKA_G11 {zones}-Zone Summary ({len(t)} samples, {np.nanmax(t):.1f}s) ===")
    for name, arr, unit in [
        ("12V Bus Voltage (ATRV)", batt_v, "V"),
        ("Target Setpoint L (0xA12A)", target_fl, "°C"),
        ("Evaporator (0xD8D7 B0)", evap, "°C"),
        ("Cabin Interior (0xD8D7 B10)", cabin, "°C"),
        ("Front Vent L / R", vent_fl, "°C"),
        ("Front Footwell L / R", foot_fl, "°C"),
        ("Rear Footwell L / R", foot_rl, "°C"),
        ("PTC Heater Duty (0xA12B B0)", ptc_duty, "%"),
        ("PTC Heater PCB Temp (0xA12B B3)", ptc_temp, "°C"),
        ("Front Foot Flap L (0xA122 B11)", flap_foot_l, "%"),
        ("Front Foot Flap R (0xA122 B12)", flap_foot_r, "%"),
        ("Front Mix Flap L (0xA122 B16)", flap_mix_l, "%"),
        ("Rear Mix Flap L (0xA122 B19)", flap_r_mix_l, "%"),
        ("Windshield Glass (0xD8D9 B3)", ws_c, "°C"),
        ("Engine Coolant (0xD8D9 B8..9)", coolant, "°C"),
    ]:
        fin = arr[np.isfinite(arr)]
        if len(fin) > 0:
            print(f"  {name:<32s}: min={np.min(fin):6.2f}{unit}  max={np.max(fin):6.2f}{unit}  std={np.std(fin):5.2f}{unit}")

    fig, (ax1, ax2, ax3, ax4, ax5) = plt.subplots(
        5, 1, figsize=(13.5, 13.8), sharex=True,
        gridspec_kw={"height_ratios": [1.0, 1.15, 1.4, 1.05, 1.15]}
    )
    fig.suptitle(f"BMW G30/G31 IHKA_G11 {zones}-Zone Climate, PTC & Flap Diagnostic — {csv_path.name}", fontsize=13, fontweight="bold")

    # Panel 1: Engine Coolant, Outside Temp, Windshield Glass & Dew Point + 12V Bus Voltage
    if np.any(np.isfinite(coolant)):
        ax1.plot(t_min, coolant, color="#d62728", lw=1.7, label="Engine Coolant (°C)")
    if np.any(np.isfinite(outside)):
        ax1.plot(t_min, outside, color="#1f77b4", lw=1.4, ls="--", label="Outside Temp (°C)")
    if np.any(np.isfinite(ws_c)):
        ax1.plot(t_min, ws_c, color="#9467bd", lw=1.6, label="Windshield Glass Temp (°C)")
    if np.any(np.isfinite(dew_c)):
        ax1.plot(t_min, dew_c, color="#2ca02c", lw=1.2, ls=":", label="Windshield Dew Point (°C)")
    ax1.set_ylabel("Temp (°C)")
    ax1.set_title("1. Engine Coolant, Outside Ambient, Windshield Condensation (RLBS) & 12V Bus Voltage", fontsize=10, loc="left")
    ax1.grid(True, alpha=0.3)

    if np.any(np.isfinite(batt_v)):
        ax1_r = ax1.twinx()
        ax1_r.plot(t_min, batt_v, color="#2e7d32", lw=1.5, alpha=0.8, label="12V Bus Voltage (V)")
        ax1_r.set_ylabel("12V Bus (V)", color="#2e7d32")
        ax1_r.tick_params(axis="y", labelcolor="#2e7d32")
        ax1_r.set_ylim(min(11.0, float(np.nanmin(batt_v)) - 0.3), max(15.5, float(np.nanmax(batt_v)) + 0.3))
        l1, lb1 = ax1.get_legend_handles_labels()
        l2, lb2 = ax1_r.get_legend_handles_labels()
        ax1.legend(l1 + l2, lb1 + lb2, loc="upper right", ncol=3, fontsize=8)
    else:
        ax1.legend(loc="upper right", ncol=3, fontsize=8)

    # Panel 2: Evaporator Core, Cabin Interior Sensor & Target Setpoint
    ax2.axhspan(-1.0, 2.0, color="#ff5252", alpha=0.14, label="Evap Icing / Cut-Out Zone (<2.0°C)")
    ax2.axhspan(2.0, 4.5, color="#00b4d8", alpha=0.12, label="Normal Evap Target Band (2.0–4.5°C)")
    ax2.axhline(0.0, color="#d32f2f", lw=0.9, ls="--")

    if np.any(np.isfinite(evap)):
        ax2.plot(t_min, evap, color="#0077b6", lw=2.0, label="Evaporator Sensor (°C)")
        spikes = detect_spikes(t, evap, threshold_c_per_s=args.spike_rate)
        if len(spikes) > 0:
            ax2.scatter(t_min[spikes], evap[spikes], color="red", edgecolors="black", s=45, zorder=6,
                        label=f"Evap Glitch (≥{args.spike_rate:.1f}°C/s)")
    if np.any(np.isfinite(cabin)):
        ax2.plot(t_min, cabin, color="#f59f00", lw=1.8, label="Cabin Interior Sensor (Undamped °C)")
    if np.any(np.isfinite(target_fl)):
        ax2.plot(t_min, target_fl, color="#2b9348", lw=1.5, ls="--", drawstyle="steps-post", label="Target Setpoint Front L (°C)")
    if np.any(np.isfinite(target_fr)) and not np.array_equal(target_fl, target_fr):
        ax2.plot(t_min, target_fr, color="#55a630", lw=1.2, ls=":", drawstyle="steps-post", label="Target Setpoint Front R (°C)")

    ax2.set_ylabel("Evap / Cabin (°C)")
    ax2.set_title("2. Evaporator Freeze-Protection Loop, Cabin Faceplate Sensor & Target Setpoint (°C)", fontsize=10, loc="left")
    ax2.grid(True, alpha=0.3)
    ax2.legend(loc="upper right", ncol=3, fontsize=8)

    # Panel 3: Duct Temperatures (4 or 8 sensors) + PTC PCB Temp
    ax3.axhline(40.0, color="#ff7f0e", lw=0.9, ls=":", alpha=0.8, label="40°C Footwell Comfort Limit")
    for arr, lbl, clr, ls in [
        (vent_fl, "Front Vent L", "#00b4d8", "-"),
        (vent_fr, "Front Vent R", "#00b4d8", "--"),
        (foot_fl, "Front Footwell L", "#e63946", "-"),
        (foot_fr, "Front Footwell R", "#e63946", "--"),
        (vent_rl, "Rear Vent L", "#2a9d8f", "-"),
        (vent_rr, "Rear Vent R", "#2a9d8f", "--"),
        (foot_rl, "Rear Footwell L", "#ff7f00", "-"),
        (foot_rr, "Rear Footwell R", "#ff7f00", "--"),
        (ptc_temp, "PTC Heater PCB Temp (0xA12B)", "#800020", "-."),
    ]:
        if np.any(np.isfinite(arr)):
            ax3.plot(t_min, arr, color=clr, ls=ls, lw=1.5, label=lbl)

    ax3.set_ylabel("Duct / PTC (°C)")
    ax3.set_title(f"3. {zones}-Zone Ventilation & Footwell Duct Temperatures (0xD8D7) + PTC PCB Temp (0xA12B)", fontsize=10, loc="left")
    ax3.grid(True, alpha=0.3)
    ax3.legend(loc="upper right", ncol=5, fontsize=7.5)

    # Panel 4: Aircon Settings & PTC Duty Cycle (0..100%)
    if np.any(np.isfinite(ptc_duty)):
        ax4.plot(t_min, ptc_duty, color="#d90429", lw=2.0, drawstyle="steps-post", label="Electric PTC Heater Duty (%)")
    if np.any(np.isfinite(blower_pct_f)):
        ax4.plot(t_min, blower_pct_f, color="#1971c2", lw=1.6, drawstyle="steps-post", label="Front Blower Power (%)")
    elif np.any(np.isfinite(blower_step_l)):
        ax4.plot(t_min, blower_step_l * 20.0, color="#1971c2", lw=1.6, drawstyle="steps-post", label="Front Blower Step (x20%)")
    if np.any(np.isfinite(blower_pct_r)):
        ax4.plot(t_min, blower_pct_r, color="#4dabf7", lw=1.2, ls="--", drawstyle="steps-post", label="Rear FKA Blower Power (%)")
    if np.any(np.isfinite(strat_l)):
        ax4.plot(t_min, strat_l, color="#9c36b5", lw=1.4, drawstyle="steps-post", label="Stratification Slider L (50%=Neutral)")
    if np.any(np.isfinite(auto_flap_l)):
        ax4.plot(t_min, auto_flap_l * 100.0, color="#2b8a3e", lw=1.3, ls="-.", drawstyle="steps-post", label="AUTO Vent Mode (100=AUTO, 0=MAN)")
    if np.any(np.isfinite(ac_on)):
        ax4.plot(t_min, ac_on * 90.0, color="#0ca678", lw=1.2, ls=":", drawstyle="steps-post", label="A/C Active (90=ON, 0=OFF)")
    if np.any(np.isfinite(sync_act)):
        ax4.plot(t_min, sync_act * 80.0, color="#e67700", lw=1.1, ls=":", drawstyle="steps-post", label="SYNC Active (80=SYNC, 0=4Z)")

    ax4.set_ylim(-5, 108)
    ax4.set_ylabel("Duty / Settings (%)")
    ax4.set_title("4. Electric PTC Heater Duty Cycle (0xA12B) & Aircon Settings (Blower %, Strat, AUTO, A/C)", fontsize=10, loc="left")
    ax4.grid(True, alpha=0.3)
    ax4.legend(loc="upper right", ncol=4, fontsize=7.5)

    # Panel 5: LIN Stepper Flap Positions (Front & Rear) & Windshield RH% / A/C Bar
    for arr, lbl, clr, ls in [
        (flap_def, "Defrost / Windshield Flap (%)", "#1d3557", "-"),
        (flap_vent_l, "Front Vent L Flap (%)", "#00b4d8", "-"),
        (flap_vent_r, "Front Vent R Flap (%)", "#00b4d8", "--"),
        (flap_foot_l, "Front Footwell L Flap (%)", "#2a9d8f", "-"),
        (flap_foot_r, "Front Footwell R Flap (%)", "#2a9d8f", "--"),
        (flap_mix_l, "Front Mix Flap L (%)", "#e63946", "-"),
        (flap_mix_r, "Front Mix Flap R (%)", "#e63946", "--"),
        (flap_r_mix_l, "Rear Mix Flap L (%)", "#ff7f00", "-"),
        (flap_r_mix_r, "Rear Mix Flap R (%)", "#ff7f00", "--"),
        (flap_r_dist_l, "Rear Foot/Vent Dist L (%)", "#6a4c93", "-"),
        (flap_r_dist_r, "Rear Foot/Vent Dist R (%)", "#6a4c93", "--"),
    ]:
        if np.any(np.isfinite(arr)):
            ax5.plot(t_min, arr, color=clr, ls=ls, lw=1.5, drawstyle="steps-post", label=lbl)
    if np.any(np.isfinite(ws_rh)):
        ax5.plot(t_min, ws_rh, color="#9467bd", lw=1.1, ls=":", label="Windshield Humidity RH (%)")
    if np.any(np.isfinite(ac_bar)):
        ax5.plot(t_min, ac_bar, color="#555555", lw=1.0, ls=":", label="A/C Pressure (bar)")

    ax5.set_ylim(-5, 108)
    ax5.set_ylabel("Flap % / RH / bar")
    ax5.set_xlabel("Elapsed Time (minutes)")
    ax5.set_title("5. Front & Rear LIN Flap Actuator Positions (31 03 A1 22), Windshield RH% & A/C Pressure", fontsize=10, loc="left")
    ax5.grid(True, alpha=0.3)
    ax5.legend(loc="upper right", ncol=5, fontsize=7.5)

    # Overlay Cockpit HOT_SWING / COLD_SWING event markers across all 5 panels
    hot_labeled = cold_labeled = False
    for idx, tag in enumerate(markers):
        if not tag or not np.isfinite(t_min[idx]):
            continue
        is_hot = "HOT" in tag.upper()
        clr = "#ff5722" if is_hot else "#0288d1"
        for ax in (ax1, ax2, ax3, ax4, ax5):
            lbl = None
            if ax is ax2:
                if is_hot and not hot_labeled:
                    lbl = "Marked HOT Blast"
                    hot_labeled = True
                elif not is_hot and not cold_labeled:
                    lbl = "Marked COLD Blast"
                    cold_labeled = True
            ax.axvline(t_min[idx], color=clr, ls="-.", lw=1.3, alpha=0.85, label=lbl)

    if hot_labeled or cold_labeled:
        ax2.legend(loc="upper right", ncol=3, fontsize=8)

    plt.tight_layout()
    if args.save:
        plt.savefig(args.save, dpi=180)
        print(f"[+] Saved plot to {args.save}")
    plt.show()


if __name__ == "__main__":
    main()
